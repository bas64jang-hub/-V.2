/**
 * คืนค่ารายการหม้อแปลงสำหรับอุปกรณ์ป้องกันที่ระบุ
 */
export function getTransformersForProtectionDevice(cutoutId: string): Transformer[] {
  return TRANSFORMERS_15.filter((t) => t.lineCutoutId === cutoutId);
}

/**
 * คืนค่าอุปกรณ์ป้องกันสำหรับหม้อแปลงที่ระบุ
 */
export function getProtectionDeviceForTransformer(transformerId: string): LineCutout | undefined {
  const norm = transformerId.replace(/\s+/g, '');
  const tr = TRANSFORMERS_15.find((t) => t.id.replace(/\s+/g, '') === norm);
  if (!tr || !tr.lineCutoutId) return undefined;
  return HIGH_VOLTAGE_PROTECTION_DEVICES.find((d) => d.id === tr.lineCutoutId);
}
